/**
 * Generates src/ids.generated.ts: a zod enum of the ids in each data file, and its union type, so
 * ids are checked and autocompleted at compile time and validated at run time. Run with `pnpm build:ids`; `pnpm check` fails when the
 * committed file is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const files = {
    JudicialAreaId: 'judicial-areas',
    ArrondissementId: 'arrondissements',
    CantonId: 'cantons',
    RegionId: 'regions',
    ProvinceId: 'provinces',
    MunicipalityId: 'municipalities',
    CourtId: 'courts',
    PrisonId: 'prisons',
    HouseOfJusticeId: 'houses-of-justice',
    PostalCodeId: 'postal-codes',
    PoliceZoneId: 'police-zones',
} as const

let out = "// Generated by scripts/build-ids.ts from data/. Do not edit.\nimport { z } from 'zod'\n"
for (const [type, file] of Object.entries(files)) {
    const records = JSON.parse(readFileSync(`data/${file}.json`, 'utf8')) as { id: string }[]
    // A record has several versions under one id
    const ids = [...new Set(records.map((record) => record.id))].sort()
    const schema = `${type.charAt(0).toLowerCase()}${type.slice(1)}Schema`
    const doc = `/** Id of a record in data/${file}.json */`
    out += `\n${doc}\nexport const ${schema} = z.enum([\n`
    out += ids.map((id) => `    '${id}',`).join('\n') + '\n])\n'
    out += `${doc}\nexport type ${type} = z.infer<typeof ${schema}>\n`
}
writeFileSync('src/ids.generated.ts', out)
